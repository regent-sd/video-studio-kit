# ---------------------------------------------------------------- reading ids without opening files

def drive_id(path):
    """Google Drive for desktop puts each item's permanent id in an extended attribute. None elsewhere."""
    if hasattr(os, "getxattr"):
        try:
            return os.getxattr(path, DRIVE_ATTR, follow_symlinks=False).decode() or None
        except OSError:
            return None
    return _drive_id_ctypes(path)


_libc = None


def _drive_id_ctypes(path):
    """macOS's Python has no os.getxattr; read the attribute through libc instead."""
    global _libc
    import ctypes
    import ctypes.util
    if _libc is None:
        _libc = ctypes.CDLL(ctypes.util.find_library("c"), use_errno=True)
        _libc.getxattr.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_size_t,
                                   ctypes.c_uint32, ctypes.c_int]
        _libc.getxattr.restype = ctypes.c_ssize_t
    buf = ctypes.create_string_buffer(256)
    n = _libc.getxattr(os.fsencode(path), DRIVE_ATTR, buf, 256, 0, 1)   # 1 = XATTR_NOFOLLOW
    return buf.raw[:n].decode() if n > 0 else None


def local_id(label, st, prefix):
    """Stable while the item stays on the same disk: renames and moves keep the inode."""
    return f"{prefix}{al.short_hash(label)}-{st.st_ino:x}"


# ---------------------------------------------------------------- walking the roots

def day(ts):
    return dt.datetime.fromtimestamp(ts).strftime("%Y-%m-%d")


def ext_of(name):
    return name.rsplit(".", 1)[1].lower() if "." in name.strip(".") else ""


def package_bytes(path):
    total = 0
    for dp, _, fn in os.walk(path):
        for f in fn:
            try:
                total += os.lstat(os.path.join(dp, f)).st_size
            except OSError:
                pass
    return total


def walk():
    """Every file (a macOS package counts as one) under every root, plus every folder and every problem."""
    assets, folders, problems, missing = [], {}, [], []

    def problem(kind, rel, detail=""):
        problems.append({"type": kind, "path": rel, "detail": detail})

    def add_folder(path, rel, label, st):
        did = drive_id(path)
        folders[rel] = {"id": did or local_id(label, st, "d"), "path": rel, "root": label, "files": 0,
                        "direct_files": 0, "subfolders": 0, "locked": al.locked(rel),
                        "link": f"https://drive.google.com/drive/folders/{did}" if did else None}

    def visit(path, rel, label):
        try:
            entries = sorted(os.scandir(path), key=lambda e: e.name)
        except OSError as e:
            problem("unreadable", rel, e.strerror or str(e))
            return
        names = {e.name for e in entries}
        has_project = any(ext_of(n) in PROJECT_EXT for n in names)
        for e in entries:
            name, r = e.name, f"{rel}/{e.name}"
            if name.startswith(".") or name == "Icon\r" or os.path.normpath(e.path) in al.EXCLUDED_DISK:
                continue
            if name != name.strip():
                problem("space-at-end-of-name", r, "name starts or ends with a space; some tools can't open it")
            if ":" in name:
                problem("slash-in-name", r, f"Finder shows it as {name.replace(':', '/')!r}")
            try:
                st = e.stat(follow_symlinks=False)
            except OSError as err:
                problem("unreadable", r, err.strerror or str(err))
                continue
            if stat.S_ISLNK(st.st_mode):
                problem("link", r, "a symbolic link or drive shortcut (not a file); not followed")
                continue
            ext = ext_of(name)
            if stat.S_ISDIR(st.st_mode) and ext not in PACKAGES:
                folders[rel]["subfolders"] += 1
                add_folder(e.path, r, label, st)
                visit(e.path, r, label)
                continue
            if not (stat.S_ISDIR(st.st_mode) or stat.S_ISREG(st.st_mode)):
                continue
            package = stat.S_ISDIR(st.st_mode)
            kind = EXT_KIND.get(ext, "other")
            if ext in SIDECAR_EXT and has_project:
                kind = "project"
            if name.endswith(" alias") and not package:
                problem("alias", r, "Finder alias (points somewhere else on one Mac; useless to anyone else)")
                kind = "other"
            if ext.startswith("tmp"):
                problem("temp-file", r, "leftover temporary file")
            did = drive_id(e.path)
            parts = r.split("/")
            assets.append({
                "id": did or local_id(label, st, "f"), "path": r, "root": label, "name": name, "ext": ext,
                "kind": kind, "bytes": package_bytes(e.path) if package else st.st_size,
                "modified": day(st.st_mtime), "created": day(getattr(st, "st_birthtime", st.st_mtime)),
                "top": parts[1] if len(parts) > 2 else "", "folder": rel, "folder_id": folders[rel]["id"],
                "drive_id": did, "link": f"https://drive.google.com/file/d/{did}/view" if did else None,
                "locked": al.locked(r), "package": package,
                "local": not (getattr(st, "st_flags", 0) & SF_DATALESS),
                "md5": None, "dup_group": None, "dup_basis": None,
                "camera_name": bool(CAMERA.match(name.rsplit(".", 1)[0] if ext else name)),
                "_stat": (st.st_dev, st.st_ino, st.st_size, st.st_mtime_ns), "_lid": local_id(label, st, "f"),
            })
            folders[rel]["direct_files"] += 1

    for label, root in al.ROOTS:
        try:
            st = os.stat(root)
        except OSError:
            missing.append(label)
            problem("missing-root", label, f"{root} is not there (an unplugged drive, or the path changed)")
            continue
        add_folder(str(root), label, label, st)
        visit(str(root), label, label)
    for a in assets:
        parts = a["path"].split("/")[:-1]
        for i in range(1, len(parts) + 1):
            folders["/".join(parts[:i])]["files"] += 1
    flist = []
    for rel, f in sorted(folders.items()):
        f["empty"] = f["files"] == 0
        flist.append(f)
    return assets, flist, problems, missing


# ---------------------------------------------------------------- content hashes (with a cache)

def hash_files(assets, enabled=True, online=False):
    """md5 of every file, reading only files that are new or changed since the last scan.
    enabled=False (scan --no-hash) still uses the hashes already known, and reads nothing."""
    cache = al.load_json(al.HASHES, {})
    cache = cache if isinstance(cache, dict) else {}
    fresh, done, read_bytes, skipped_online, t0, last = {}, 0, 0, 0, time.time(), time.time()
    for a in assets:
        dev, ino, size, mtime = a.pop("_stat")
        if a["package"]:
            continue
        key = f"{dev}:{ino}"
        hit = cache.get(key)
        if isinstance(hit, list) and hit[:2] == [size, mtime]:
            a["md5"] = hit[2]
            fresh[key] = hit
            continue
        if not enabled:
            continue
        if not a["local"] and not online:
            skipped_online += 1
            continue
        try:
            with open(al.to_disk(a["path"]), "rb") as fh:
                a["md5"] = hashlib.file_digest(fh, "md5").hexdigest()
        except OSError:
            continue
        fresh[key] = [size, mtime, a["md5"]]
        done += 1
        read_bytes += size
        if time.time() - last > 5:
            print(f"  hashing: {done} files, {al.gb(read_bytes)} read", flush=True)
            last = time.time()
    al.atomic_write(al.HASHES, json.dumps(fresh if enabled else {**cache, **fresh}, separators=(",", ":")))
    note = f"hashed {done} new or changed files ({al.gb(read_bytes)}) in {time.time() - t0:.0f} s"
    if skipped_online:
        note += f"; {skipped_online} online-only files not downloaded (scan --hash-online to hash them)"
    return note if enabled else f"--no-hash: used {len(fresh)} known hashes and read no files"


# ---------------------------------------------------------------- duplicates

def mark_dups(assets):
    """Same md5 = certain. Without an md5: same size and extension (probable), or name+size when names match too."""
    groups = {}
    for a in assets:
        if a["package"] or a["bytes"] < (DUP_MIN_MD5 if a["md5"] else DUP_MIN_SIZE):
            continue
        key = f"m-{a['md5'][:12]}" if a["md5"] else f"s-{a['ext'] or 'none'}-{a['bytes']}"
        groups.setdefault(key, []).append(a)
    for key, members in groups.items():
        if len(members) < 2:
            continue
        basis = "md5" if key.startswith("m-") else ("name+size" if len({m["name"].lower() for m in members}) == 1 else "size")
        for m in members:
            m["dup_group"], m["dup_basis"] = key, basis


def removable(members):
    """Copies that could go while keeping one, and never a locked one."""
    return len(members) - max(1, sum(m["locked"] for m in members))


def dup_groups(assets):
    g = {}
    for a in assets:
        if a.get("dup_group"):
            g.setdefault(a["dup_group"], []).append(a)
    return sorted(g.items(), key=lambda kv: -(len(kv[1]) - 1) * kv[1][0]["bytes"])


# ---------------------------------------------------------------- merging later steps' fields

def merge_later(assets):
    """Keep what later steps wrote, per content: the old catalog first, then media.json, then tags/*.json oldest
    to newest (a later file wins per key). Each is looked up by md5 first, then by the file's id."""
    old = {}
    for a in al.load_json(al.CATALOG, {}).get("assets", []):
        for k in (a.get("md5"), a.get("id")):
            if k:
                old.setdefault(k, a)
    media = al.load_json(al.MEDIA_FILE, {})
    media = media if isinstance(media, dict) else {}
    tag_files = sorted(al.TAGS_DIR.glob("*.json"), key=lambda p: p.stat().st_mtime) if al.TAGS_DIR.exists() else []
    tag_sets = [(p.name, al.load_json(p, None)) for p in tag_files]
    bad = [n for n, d in tag_sets if not isinstance(d, dict)]
    merged = {"media": 0, "tags": 0}
    for a in assets:
        keys = [k for k in (a["md5"], a["id"]) if k]
        for k, v in LATER.items():
            a[k] = json.loads(json.dumps(v))
        o = old.get(a["md5"] or a["id"])     # by id only when there's no md5: an edited file starts fresh
        if o:
            for k in LATER:
                if o.get(k) not in (None, {}, []):
                    a[k] = o[k]
        m = next((media[k] for k in keys if isinstance(media.get(k), dict)), None)
        if m:
            for k in MEDIA_KEYS:
                if k in m:
                    a[k] = m[k]
            merged["media"] += 1
        hit = False
        for _, d in tag_sets:
            if not isinstance(d, dict):
                continue
            t = next((d[k] for k in keys if isinstance(d.get(k), dict)), None)
            if t:
                for k in TAG_KEYS:
                    if k in t:
                        a[k] = t[k]
                hit = True
        merged["tags"] += hit
    return merged, [p.name for p in tag_files], bad


# ---------------------------------------------------------------- writing

def flat_tags(t):
    if isinstance(t, dict):
        return "; ".join(f"{k}: {', '.join(map(str, v)) if isinstance(v, list) else v}" for k, v in t.items())
    return ", ".join(map(str, t)) if isinstance(t, list) else str(t or "")


def write_csv(assets):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Name", "Kind", "Root", "Top folder", "Folder", "Size (MB)", "Modified", "Link", "Duplicate group",
                "Duplicate basis", "Locked", "Description", "Tags", "Flags", "Brand status", "ID", "MD5"])
    for a in assets:
        w.writerow([a["name"], a["kind"], a["root"], a["top"], a["folder"], f"{a['bytes'] / 1e6:.2f}", a["modified"],
                    a["link"] or "", a["dup_group"] or "", a["dup_basis"] or "", "yes" if a["locked"] else "",
                    a["description"] or "", flat_tags(a["tags"]), ", ".join(a["flags"] or []), a["brand_status"] or "",
                    a["id"], a["md5"] or ""])
    al.atomic_write(al.CSV_FILE, buf.getvalue(), encoding="utf-8-sig")


def counts(assets, folders, problems):
    def tally(fn):
        out = {}
        for a in assets:
            c = out.setdefault(fn(a), {"files": 0, "bytes": 0})
            c["files"] += 1
            c["bytes"] += a["bytes"]
        return dict(sorted(out.items(), key=lambda kv: -kv[1]["bytes"]))
    dups = {}
    for _, members in dup_groups(assets):
        d = dups.setdefault(members[0]["dup_basis"], {"groups": 0, "extra_copies": 0, "extra_bytes": 0, "removable_bytes": 0})
        d["groups"] += 1
        d["extra_copies"] += len(members) - 1
        d["extra_bytes"] += (len(members) - 1) * members[0]["bytes"]
        d["removable_bytes"] += removable(members) * members[0]["bytes"]
    probs = {}
    for p in problems:
        probs[p["type"]] = probs.get(p["type"], 0) + 1
    return {"files": len(assets), "bytes": sum(a["bytes"] for a in assets), "folders": len(folders),
            "empty_folders": sum(f["empty"] for f in folders), "locked_files": sum(a["locked"] for a in assets),
            "online_only": sum(not a["local"] for a in assets), "with_md5": sum(bool(a["md5"]) for a in assets),
            "camera_names": sum(a["camera_name"] for a in assets), "tagged": sum(bool(a["description"]) for a in assets),
            "by_kind": tally(lambda a: a["kind"]),
            "by_top": tally(lambda a: f"{a['root']}/{a['top']}" if a["top"] else f"{a['root']} (loose files)"),
            "duplicates": dups, "problems": probs}


def summary(doc):
    c = doc["counts"]
    print(f"{c['files']} files, {al.gb(c['bytes'])}, in {c['folders']} folders ({c['empty_folders']} empty) - {doc['generated']}")
    print(f"locked {c['locked_files']}, online-only {c['online_only']}, with md5 {c['with_md5']}, "
          f"camera-style names {c['camera_names']}, tagged {c.get('tagged', 0)}")
    for title, key in (("By kind", "by_kind"), ("By top folder", "by_top")):
        print(f"\n{title}:")
        for k, v in c[key].items():
            print(f"  {k:<46} {v['files']:>6}  {al.gb(v['bytes']):>9}")
    print("\nDuplicates:" + ("" if c["duplicates"] else " none"))
    for basis, d in c["duplicates"].items():
        print(f"  {basis:<10} {d['groups']:>5} groups, {d['extra_copies']:>5} extra copies, {al.gb(d['extra_bytes'])} "
              f"({al.gb(d.get('removable_bytes', 0))} without touching locked copies)")
    print("\nProblems: " + (", ".join(f"{k} {v}" for k, v in c["problems"].items()) or "none"))
    if doc.get("notes"):
        print("Notes: " + "; ".join(doc["notes"]))


# ---------------------------------------------------------------- commands

def scan(args):
    al.need_roots()
    use_hash, online, allow_missing = not al.flag(args, "--no-hash"), al.flag(args, "--hash-online"), al.flag(args, "--allow-missing")
    t0 = time.time()
    assets, folders, problems, missing = walk()
    if missing and not allow_missing:
        had = {a.get("root") for a in al.load_json(al.CATALOG, {}).get("assets", [])}
        gone = [m for m in missing if m in had]
        if gone:
            sys.exit(f"Root(s) not there: {', '.join(gone)}. The catalog was not rewritten, so nothing is lost. "
                     "Plug the drive in (or fix asset_roots), or scan --allow-missing to drop them.")
    notes = [hash_files(assets, use_hash, online)]
    seen = {}
    for a in assets:
        if a["drive_id"]:
            seen.setdefault(a["drive_id"], []).append(a)
    for did, ms in seen.items():
        if len(ms) > 1:            # a copy made in Finder keeps the original's id attribute: trust neither
            problems.append({"type": "copied-drive-id", "path": ms[0]["path"], "detail":
                             f"{len(ms)} files carry Drive id {did} (a copy made in Finder keeps the original's); "
                             "their Drive links are left out. Also at " + "; ".join(m["path"] for m in ms[1:])})
            for m in ms:
                m["drive_id"] = m["link"] = None
                m["id"] = m["_lid"]
    for a in assets:
        a.pop("_lid", None)
    mark_dups(assets)
    merged, tag_files, bad = merge_later(assets)
    for n in bad:
        problems.append({"type": "bad-tags-file", "path": f"tags/{n}", "detail": "not a JSON object; skipped"})
    if al.MEDIA_FILE.exists() and not isinstance(al.load_json(al.MEDIA_FILE, None), dict):
        problems.append({"type": "bad-media-file", "path": "media.json", "detail": "not a JSON object; skipped"})
    notes.append(f"merged media for {merged['media']} and tags for {merged['tags']} files from {len(tag_files)} tags files")
    w = al.icloud_warning(al.CACHE)
    if w:
        notes.append(w)
    doc = {"about": "Generated by assets/catalog.py scan. Don't edit: add fields through media.json and tags/*.json.",
           "generated": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
           "roots": [{"name": n, "path": str(p)} for n, p in al.ROOTS], "excluded": al.EXCLUDED,
           "never_move": al.NEVER_MOVE, "notes": notes, "counts": counts(assets, folders, problems),
           "assets": assets, "folders": folders, "problems": problems}
    al.atomic_write(al.CATALOG, json.dumps(doc, indent=1, ensure_ascii=False))
    write_csv(assets)
    if not (al.LIB / "README.txt").exists():
        al.atomic_write(al.LIB / "README.txt", OUT_README)
    summary(doc)
    print(f"\nWrote {al.CATALOG} and {al.CSV_FILE.name} in {time.time() - t0:.0f} s")


def parse_find(args):
    f = {"kind": al.opt(args, "--kind"), "root": al.opt(args, "--root"), "top": al.opt(args, "--top"),
         "ext": al.opt(args, "--ext"), "limit": int(al.opt(args, "--limit", "50")), "json": al.flag(args, "--json"),
         "locked": al.flag(args, "--locked"), "unlocked": al.flag(args, "--unlocked"),
         "all_copies": al.flag(args, "--all-copies"), "to_delete": al.flag(args, "--to-delete"),
         "brand": al.opt(args, "--brand"), "year": al.opt(args, "--year"), "rating": al.opt(args, "--rating")}
    f["tags"] = {k: [v.lower() for v in (al.opt(args, "--" + k) or "").split(",") if v]
                 for k in ("type", "subject", "location", "use", "setting", "campaign", "item", "people")}
    f["want"] = [x for x in (al.opt(args, "--flag") or "").split(",") if x]
    f["avoid"] = [x for x in (al.opt(args, "--not-flag") or "").split(",") if x]
    f["words"] = [w.lower() for w in args]
    return f


def search(assets, f):
    """[(asset, extra copies)] best first. Shared by find and anything else that wants the same search."""
    top = (f.get("top") or "").lower()
    hits, seen = [], {}
    for a in assets:
        if f.get("kind") and a["kind"] != f["kind"] or f.get("ext") and a["ext"] != f["ext"].lower().lstrip("."):
            continue
        if f.get("root") and a["root"].lower() != f["root"].lower():
            continue
        if top and top not in (a["top"].lower(), f"{a['root']}/{a['top']}".lower()):
            continue
        if f.get("locked") and not a["locked"] or f.get("unlocked") and a["locked"]:
            continue
        if not f.get("to_delete") and al.in_to_delete(a["folder"]):
            continue
        tags, flags = a.get("tags") or {}, a.get("flags") or []
        ok = True
        for k, vals in (f.get("tags") or {}).items():
            if vals:
                have = tags.get(k)
                have = [str(x).lower() for x in (have if isinstance(have, list) else [have] if have else [])]
                ok = ok and any(v in h for v in vals for h in have)
        if f.get("brand") and (a.get("brand_status") or "") != f["brand"].lower():
            ok = False
        if f.get("year") and str(tags.get("year")) != str(f["year"]):
            ok = False
        if f.get("rating") and (tags.get("rating") or 0) < int(f["rating"]):
            ok = False
        if f.get("want") and not any(x in flags for x in f["want"]) or any(x in flags for x in f.get("avoid") or []):
            ok = False
        if not ok:
            continue
        hay = " ".join([a["path"], a.get("description") or "", flat_tags(tags), " ".join(flags),
                        a.get("brand_status") or "", a["kind"]]).lower()
        words = f.get("words") or []
        if not all(w in hay for w in words):
            continue
        score = sum(w in a["name"].lower() for w in words) + sum(w in (a.get("description") or "").lower() for w in words)
        archived = a["top"].lower() in ("archive", "archives", "old")
        copyish = bool(COPY_NAME.search(a["name"].rsplit(".", 1)[0]))
        row = (-(tags.get("rating") or 0), -score, a["locked"], (archived, copyish), a["path"], a)
        key = al.key_of(a)
        if f.get("all_copies"):
            hits.append([row, 0])
        elif key not in seen:
            seen[key] = [row, 0]
            hits.append(seen[key])
        else:
            seen[key][1] += 1
            if row[2:5] < seen[key][0][2:5]:
                seen[key][0] = row
    hits.sort(key=lambda h: h[0][:5])
    return [(h[0][5], h[1]) for h in hits]


def find(args):
    f = parse_find(args)
    hits = search(al.load_catalog()["assets"], f)
    shown = hits[:f["limit"]]
    if f["json"]:
        out = []
        for a, extra in shown:
            a = dict(a, full_path=str(al.to_disk(a["path"])) if a["root"] in al.ROOT_BY_LABEL else None)
            if extra:
                a["other_copies"] = extra
            out.append(a)
        print(json.dumps(out, indent=1, ensure_ascii=False))
        return
    for a, extra in shown:
        t = a.get("tags") or {}
        bits = [str(x) for x in (t.get("type"), t.get("use"), a.get("brand_status"),
                                 f"rating {t['rating']}" if t.get("rating") else None) if x]
        if a.get("flags"):
            bits.append("flags: " + ", ".join(a["flags"]))
        if a["locked"]:
            bits.append("locked")
        if extra:
            bits.append(f"+{extra} more copies")
        where = a["link"] or (str(al.to_disk(a["path"])) if a["root"] in al.ROOT_BY_LABEL else "")
        print(f"{a['kind']:<13} {al.gb(a['bytes']):>9}  {a['path']}\n{'':24}{where}"
              + (f"\n{'':24}{a['description']}" if a.get("description") else "")
              + (f"\n{'':24}[{' | '.join(bits)}]" if bits else ""))
    print(f"{len(hits)} matches" + (f" (showing {f['limit']}; use --limit)" if len(hits) > f["limit"] else ""))


def dups(args):
    pairs, limit = al.flag(args, "--pairs"), int(al.opt(args, "--limit", "40"))
    groups = dup_groups(al.load_catalog()["assets"])
    if pairs:
        leaf = al.flag(args, "--leaf")

        def rollup(a, b):
            """Mirrored trees count once: A/x/y and B/x/y roll up to A/x and B/x (unless --leaf)."""
            a, b = a.split("/"), b.split("/")
            while not leaf and len(a) > 1 and len(b) > 1 and a[-1] == b[-1] and a[-2] == b[-2]:
                a, b = a[:-1], b[:-1]
            return "/".join(a), "/".join(b)

        tally = {}
        for _, members in groups:
            dirs = sorted({m["folder"] for m in members})
            keys = {rollup(dirs[i], dirs[j]) for i in range(len(dirs)) for j in range(i + 1, len(dirs))}
            if len(dirs) == 1:
                keys.add((dirs[0], dirs[0]))
            for k in keys:
                t = tally.setdefault(k, [0, 0])
                t[0] += 1
                t[1] += members[0]["bytes"]
        for (a, b), (n, size) in sorted(tally.items(), key=lambda kv: -kv[1][0])[:limit]:
            print(f"{n:>5} files {al.gb(size):>9}  {a}" + ("  (within the folder)" if a == b else f"\n{'':22}= {b}"))
        return
    total = sum((len(m) - 1) * m[0]["bytes"] for _, m in groups)
    free = sum(removable(m) * m[0]["bytes"] for _, m in groups)
    print(f"{len(groups)} groups, {sum(len(m) - 1 for _, m in groups)} extra copies, {al.gb(total)} reclaimable "
          f"({al.gb(free)} without touching locked copies)\n")
    for key, members in groups[:limit]:
        print(f"{key}  {members[0]['dup_basis']}  {len(members)} x {al.gb(members[0]['bytes'])}  "
              f"(save {al.gb((len(members) - 1) * members[0]['bytes'])})")
        for m in members:
            print(f"    {'[locked] ' if m['locked'] else ''}{m['path']}")
    if len(groups) > limit:
        print(f"... {len(groups) - limit} more groups (use --limit)")


def main():
    args = sys.argv[1:]
    cmd = args.pop(0) if args else ""
    if cmd == "scan":
        scan(args)
    elif cmd == "stats":
        summary(al.load_catalog())
    elif cmd == "find":
        find(args)
    elif cmd == "dups":
        dups(args)
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
